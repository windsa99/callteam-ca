'use strict';
const assert = require('node:assert/strict');
const model = require('../src/assets/js/award-engagement');
const home = 'https://www.callteam.ca';
const page = home + '/awards/global-excellence-2027/';
const now = Date.now();
const start = model.begin('globalexcellence', home + '/pricing/?email=private@example.com#contact', 'footer', now);
assert.equal(start.origin, '/pricing/');
assert(!JSON.stringify(start).includes('private'));
assert.equal(model.begin('invented', '/', 'footer', now), null);
assert.equal(model.read('bad JSON', now), null);
assert.equal(model.read(JSON.stringify(start), now + model.timeout + 1), null);
assert.equal(model.read(JSON.stringify({...start, time: now + 1}), now), null);
assert.equal(model.action(page, home + '/pricing/', null).event, 'ct_award_badge_click');
assert.equal(model.action('/case-studies/saas-demo-appointment-setting/', page, start).event, 'ct_award_proof_click');
assert.equal(model.action('/services/outsourced-sdr/', page, start).event, 'ct_award_service_click');
assert.equal(model.action('/b2b-outbound-campaign-planner/', page, start).event, 'ct_award_tool_click');
const booking = 'https://calendly.com/hello-callteam/new-meeting?utm_content=preserved';
assert.equal(model.action(booking, home + '/pricing/', start).event, 'ct_award_booking_click');
assert.equal(model.action(booking, page, null), null);
assert.equal(model.action('https://calendly.com.evil.test/hello-callteam/new-meeting', page, start), null);
assert.equal(model.action('https://outside.test/awards/global-excellence-2027/', page, start), null);
assert.equal(model.action('mailto:hello@callteam.ca', page, start), null);
assert.equal(model.action('#campaign-evidence', page, start), null);
let listener, stored, events = [], attrs = {};
const doc = { documentElement: { getAttribute: n => attrs[n], setAttribute: (n, v) => { attrs[n] = v; } }, addEventListener: (name, fn) => { assert.equal(name, 'click'); listener = fn; } };
const win = {document: doc, location: {href: page}, sessionStorage: {getItem: () => stored, setItem: (k, v) => { assert.equal(k, model.storageKey); stored = v; }}, clarity: (...args) => events.push(args)};
model.bind(win);
assert(events.some(e => e[0] === 'event' && e[1] === 'ct_award_announcement_view'));
const a = {href: booking, getAttribute: () => null, closest: () => null};
let prevented = false;
listener({target: {closest: () => a}, preventDefault: () => {prevented = true;}});
assert.equal(a.href, booking); assert.equal(prevented, false);
assert(events.some(e => e[0] === 'event' && e[1] === 'ct_award_booking_click'));
assert(!JSON.stringify(events).includes('utm_content'));
const fourthPage = home + '/awards/corporate-livewire-global-awards-2026-27/';
const fourthState = model.begin('corporatelivewire', home + '/services/outsourced-sdr/?private=hidden', 'services-awards', now);
assert.equal(fourthState.award, 'corporatelivewire');
assert.equal(fourthState.origin, '/services/outsourced-sdr/');
assert.equal(model.action(fourthPage, page, start).award, 'corporatelivewire');
assert.equal(model.action('/case-studies/hr-software-lead-generation/', fourthPage, fourthState).event, 'ct_award_proof_click');
assert.equal(model.action(booking, fourthPage, fourthState).award, 'corporatelivewire');
assert.equal(model.action('https://outside.test/awards/corporate-livewire-global-awards-2026-27/', fourthPage, fourthState), null);
const count = events.length; model.bind(win); assert.equal(events.length, count);
assert.equal(attrs['data-award-engagement'], 'ready');
console.log('Award journey checks passed: privacy, expiry, attribution, relevant navigation, existing booking URL and normal link behaviour.');
